# --- executable / invocation-shape resolution --------------------------------

def resolve_real_executable() -> str:
    """The real Codex binary this mux proxies to -- never itself.

    The explicit environment override wins.  The coordinator may otherwise
    pin the exact extension-bundled binary in the private sideband directory;
    this avoids accidentally proxying a different ``codex`` from PATH.
    """
    override = os.environ.get(ENV_REAL_EXECUTABLE)
    if override:
        return override
    config = default_sideband_dir() / REAL_EXECUTABLE_CONFIG_NAME
    try:
        st = os.lstat(config)
        if (
            stat.S_ISREG(st.st_mode)
            and _owned_by_current_user(st)
            and _private_mode(st, 0o600)
            and st.st_size <= 4096
        ):
            candidate = config.read_text(encoding="utf-8").strip()
            if os.path.isabs(candidate) and os.path.isfile(candidate) and os.access(candidate, os.X_OK):
                return candidate
    except OSError:
        pass
    return DEFAULT_REAL_EXECUTABLE


def _close_windows_handle(handle: int | None) -> None:
    """Close one exact Windows kernel handle owned by this process."""

    if os.name != "nt" or not handle:
        return
    with contextlib.suppress(OSError):  # pragma: no cover - Windows kernel call
        kernel32 = ctypes.windll.kernel32
        kernel32.CloseHandle.argtypes = [wintypes.HANDLE]
        kernel32.CloseHandle.restype = wintypes.BOOL
        kernel32.CloseHandle(wintypes.HANDLE(handle))


def _bind_child_lifetime_to_this_process(child: subprocess.Popen[Any]) -> int | None:
    """Best-effort Windows Job Object with KILL_ON_JOB_CLOSE.

    VS Code tracks the mux parent, not the real Codex child.  Binding that
    child to a job owned by the mux prevents reload/crash paths from leaving
    an orphan with detached stdio.  Failure is deliberately non-fatal: the
    transparent proxy remains usable on restricted Windows hosts.
    """

    if os.name != "nt":
        return None

    class _IO_COUNTERS(ctypes.Structure):  # pragma: no cover - Windows only
        _fields_ = [
            ("ReadOperationCount", ctypes.c_ulonglong),
            ("WriteOperationCount", ctypes.c_ulonglong),
            ("OtherOperationCount", ctypes.c_ulonglong),
            ("ReadTransferCount", ctypes.c_ulonglong),
            ("WriteTransferCount", ctypes.c_ulonglong),
            ("OtherTransferCount", ctypes.c_ulonglong),
        ]

    class _BASIC_LIMIT(ctypes.Structure):  # pragma: no cover - Windows only
        _fields_ = [
            ("PerProcessUserTimeLimit", ctypes.c_longlong),
            ("PerJobUserTimeLimit", ctypes.c_longlong),
            ("LimitFlags", wintypes.DWORD),
            ("MinimumWorkingSetSize", ctypes.c_size_t),
            ("MaximumWorkingSetSize", ctypes.c_size_t),
            ("ActiveProcessLimit", wintypes.DWORD),
            ("Affinity", ctypes.c_size_t),
            ("PriorityClass", wintypes.DWORD),
            ("SchedulingClass", wintypes.DWORD),
        ]

    class _EXTENDED_LIMIT(ctypes.Structure):  # pragma: no cover - Windows only
        _fields_ = [
            ("BasicLimitInformation", _BASIC_LIMIT),
            ("IoInfo", _IO_COUNTERS),
            ("ProcessMemoryLimit", ctypes.c_size_t),
            ("JobMemoryLimit", ctypes.c_size_t),
            ("PeakProcessMemoryUsed", ctypes.c_size_t),
            ("PeakJobMemoryUsed", ctypes.c_size_t),
        ]

    kernel32 = ctypes.windll.kernel32  # pragma: no cover - Windows only
    kernel32.CreateJobObjectW.argtypes = [ctypes.c_void_p, wintypes.LPCWSTR]
    kernel32.CreateJobObjectW.restype = wintypes.HANDLE
    kernel32.SetInformationJobObject.argtypes = [
        wintypes.HANDLE,
        ctypes.c_int,
        ctypes.c_void_p,
        wintypes.DWORD,
    ]
    kernel32.SetInformationJobObject.restype = wintypes.BOOL
    kernel32.AssignProcessToJobObject.argtypes = [wintypes.HANDLE, wintypes.HANDLE]
    kernel32.AssignProcessToJobObject.restype = wintypes.BOOL
    job = kernel32.CreateJobObjectW(None, None)
    if not job:
        return None
    job_value = int(job) if isinstance(job, int) else int(job.value)
    info = _EXTENDED_LIMIT()
    info.BasicLimitInformation.LimitFlags = 0x00002000
    if not kernel32.SetInformationJobObject(
        job,
        9,
        ctypes.byref(info),
        ctypes.sizeof(info),
    ):
        _close_windows_handle(job_value)
        return None
    process_handle = getattr(child, "_handle", None)
    if not process_handle or not kernel32.AssignProcessToJobObject(
        job,
        wintypes.HANDLE(int(process_handle)),
    ):
        _close_windows_handle(job_value)
        return None
    return job_value


def _hold_passthrough_child(real_executable: str, argv: list[str]) -> int:
    """Keep the Windows PID tracked by VS Code alive until Codex exits."""

    child = subprocess.Popen([real_executable, *argv], shell=False)
    job_handle = _bind_child_lifetime_to_this_process(child)
    try:
        return int(child.wait())
    except KeyboardInterrupt:
        with contextlib.suppress(OSError):
            child.terminate()
        with contextlib.suppress(subprocess.TimeoutExpired, OSError):
            child.wait(timeout=5)
        return 130
    finally:
        _close_windows_handle(job_handle)


def is_app_server_invocation(argv: list[str]) -> bool:
    """``True`` iff ``argv`` (this process's own args, minus argv[0]) asks
    for the App Server subcommand -- the only shape this module proxies;
    every other invocation is a transparent ``execvp`` passthrough."""
    return APP_SERVER_ARG in argv


def resolve_repo_id_for_mux() -> str:
    """Resolve the one repository owned by this Codex extension host.

    VS Code may isolate AIWorkHub and OpenAI extensions while still launching
    the Codex CLI from the repository window's extension-host process. Runtime
    ``process.env`` mutation is therefore not a reliable cross-extension
    transport. Prefer an explicit immutable binding when one is inherited;
    otherwise resolve exactly one live shared route whose recorded
    ``extension_host_pid`` equals this launcher's parent PID. Zero or multiple
    matches remain unbound and take the transparent passthrough path.
    """

    explicit = os.environ.get(ENV_REPO_ID, "").strip()
    if explicit:
        return _validate_repo_id(explicit)
    if shared_router is None:
        return ""
    try:
        registry = shared_router.list_known_repositories(limit=64)
    except (OSError, RuntimeError, TypeError, ValueError):
        return ""
    if not isinstance(registry, dict) or not registry.get("ok"):
        return ""
    parent_pid = extension_host_parent_pid()
    matches = [
        str(record.get("repo_id") or "")
        for record in registry.get("repositories", [])
        if isinstance(record, dict)
        and int(record.get("extension_host_pid") or 0) == parent_pid
        and bool(record.get("extension_host_alive"))
        and not bool(record.get("stale"))
        and str(record.get("selected_provider") or "").strip().lower() == "codex"
    ]
    if len(matches) != 1:
        return ""
    try:
        return _validate_repo_id(matches[0])
    except ValueError:
        return ""


def resolve_repo_root_for_mux(repo_id: str) -> Path | None:
    """Resolve one live, exact-parent repository root for ``repo_id``.

    Roots are accepted only from ``shared_router`` records that already
    validated the on-disk repository manifest.  The extension-host PID match
    prevents another window's selected repository from becoming this chat's
    cwd in a multi-window or multi-root session.
    """

    if shared_router is None:
        return None
    try:
        validated = _validate_repo_id(repo_id)
        registry = shared_router.list_known_repositories(limit=64)
    except (OSError, RuntimeError, TypeError, ValueError):
        return None
    if not isinstance(registry, dict) or not registry.get("ok"):
        return None
    parent_pid = extension_host_parent_pid()
    matches = [
        record
        for record in registry.get("repositories", [])
        if isinstance(record, dict)
        and str(record.get("repo_id") or "") == validated
        and int(record.get("extension_host_pid") or 0) == parent_pid
        and bool(record.get("extension_host_alive"))
        and not bool(record.get("stale"))
        and str(record.get("selected_provider") or "").strip().lower() == "codex"
    ]
    if len(matches) != 1:
        return None
    raw_root = str(matches[0].get("repo_root") or "").strip()
    if not raw_root:
        return None
    try:
        root = Path(raw_root).expanduser().resolve(strict=True)
    except (OSError, RuntimeError):
        return None
    return root if root.is_dir() else None


def bind_request_repository_context(raw_line: bytes, repo_root: Path | None) -> bytes:
    """Bind one chat lifecycle request to the verified current repository.

    Non-context requests remain byte-transparent.  For thread creation,
    resume/fork and each new turn, only ``params.cwd`` is replaced.  The root
    must already come from the exact-parent shared route above; malformed
    messages fail open to the original bytes instead of being reconstructed.
    """

    if repo_root is None:
        return raw_line
    message = _try_parse_json_object(raw_line)
    if message is None or message.get("method") not in REPOSITORY_CONTEXT_METHODS:
        return raw_line
    params = message.get("params")
    if not isinstance(params, dict):
        return raw_line
    root_text = str(repo_root)
    if params.get("cwd") == root_text:
        return raw_line
    updated = dict(message)
    updated["params"] = {**params, "cwd": root_text}
    newline = b"\r\n" if raw_line.endswith(b"\r\n") else b"\n"
    return json.dumps(updated, ensure_ascii=False, separators=(",", ":")).encode(
        "utf-8"
    ) + newline


def wait_for_repo_id_for_mux() -> str:
    """Wait briefly for this extension host to publish its repo route.

    VS Code starts extensions concurrently. The OpenAI extension can invoke
    the configured mux a few milliseconds before AIWorkHub has written its
    extension-host-PID route record. Immediate passthrough makes that one
    startup race permanent for the lifetime of the Codex app-server. Poll a
    small bounded window, then retain the existing fail-open passthrough if
    no unique exact-parent route appears.
    """

    raw_timeout = os.environ.get(ENV_ROUTE_WAIT_SECONDS, str(DEFAULT_ROUTE_WAIT_SECONDS))
    try:
        timeout = max(0.0, min(float(raw_timeout), 30.0))
    except (TypeError, ValueError):
        timeout = DEFAULT_ROUTE_WAIT_SECONDS
    deadline = time.monotonic() + timeout
    while True:
        repo_id = resolve_repo_id_for_mux()
        if repo_id:
            return repo_id
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            return ""
        time.sleep(min(ROUTE_WAIT_POLL_SECONDS, remaining))


