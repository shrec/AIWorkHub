"""Transparent Codex CLI wrapper + extension-owned App Server sideband mux.

B409: the measured defect is topology, not protocol. The VS Code OpenAI
extension spawns its OWN ``codex app-server`` child over a private stdio
pipe and owns the visible chat thread on it. A separately spawned bridge
App Server process (``callback_bridge.py``'s ``AppServerClient``) can only
ever see that same thread from the OUTSIDE -- to it, the thread looks idle
even while the extension's own App Server has it active, because
``thread/resume``/``turn/*`` are scoped to the App Server instance that
owns the turn, not to the thread id in the abstract. Spawning a second App
Server instance can never wake the extension's visible UI; it can only
start a hidden, invisible turn on a hidden connection (``B407``'s
``turn/steer``, done against the WRONG instance, does not fix this).

The fix is topological: install this module as the extension's
an explicitly verified same-host ``chatgpt.cliExecutable`` deployment (see
``scripts/install_vscode_app_server_mux.py`` -- print-config only; AIWorkHub
never applies the application-scoped setting). Two invocation shapes:

- Non-app-server invocation (``codex exec ...`` etc): ``main()`` execs the
  real Codex binary with the EXACT argv it received via ``os.execvp`` --
  full process-image replacement, so exit code and stdio are byte-
  identical to invoking the real binary directly. No proxying, no thread,
  no wrapper artifact of any kind survives this path.
- ``app-server`` invocation: the wrapper becomes the ONE process standing
  between the extension (its own stdin/stdout/stderr, inherited from VS
  Code) and a freshly spawned REAL ``codex app-server`` child (exact argv
  forwarded unchanged). ``AppServerMux`` proxies extension<->child stdio
  transparently in both directions -- requests, responses, and
  server-originated notifications all pass through byte-for-byte -- while
  additionally listening on one local Unix "sideband" socket. A trusted
  same-host, same-uid caller (``callback_bridge.py``'s
  ``SidebandCallbackClient``) can inject exactly one of
  ``thread/resume``/``turn/steer``/``turn/start`` onto the SAME child App
  Server connection the extension already owns -- using a collision-free
  synthetic wire id so its response is intercepted and routed back over
  the socket instead of leaking into the extension's stdout, while every
  server notification generated by that same call (``turn/started``,
  ``turn/completed``, etc) still flows to the extension normally, so the
  visible UI updates exactly as if the user had typed it.

Sideband trust model (fail-closed, local-only, no fallback):
- Unix socket in a private (0700) owner-only directory, socket mode 0600.
- ``SO_PEERCRED`` same-uid check on every accepted connection where the
  platform supports it.
- A separate 0600 capability-token file; the token is compared with
  ``hmac.compare_digest`` (constant-time), never ``==``.
- Exactly three allowlisted methods (``thread/resume``, ``turn/steer``,
  ``turn/start``); ``initialize`` and every other method are rejected.
  A request may carry only ``cap``/``method``/``params`` -- any other key
  (a client-supplied ``id``, a ``jsonrpc`` member, or anything else
  asserting extra transport authority) is rejected outright.
- Bounded request/response sizes and a bounded per-call deadline.
- Sideband requests are served only after this mux has passively observed
  the successful response to the EXTENSION's own correlated ``initialize``
  request on the child connection it owns -- never originated by the mux
  itself. Older clients may also send the legacy ``initialized`` notification,
  but current Codex VS Code clients do not. Before readiness, on socket loss,
  or on any malformed/
  unexpected shape, a sideband call fails closed with a bounded deferral
  (``SidebandNotReady``) for the caller to retry later. This mux NEVER
  spawns a second/separate App Server as a fallback -- that reintroduces
  the exact B407/B409 hidden-turn defect this module exists to close.
- No token, thread id, or prompt/turn text is ever written to a log file
  or printed by this module. When the repository owner explicitly enables
  Manager Context Graph, authoritative final ``userMessage``/``agentMessage``
  items are asynchronously persisted in that repository's canonical
  transcript database; reasoning, tool output and streaming deltas are never
  captured.

B472: several VS Code extension-host windows run concurrent mux processes
against the SAME ``sideband_dir``. A fixed shared socket/capability path
let the newest process silently shadow an older, still-live instance's
endpoint -- the measured B471 live-canary blocker (three concurrent mux
PIDs, one fixed ``sideband.sock``/``sideband.cap``). Each mux instance now
binds its OWN randomly-named socket/capability pair (never unlinking an
existing path -- a collision regenerates a fresh id and retries) and
publishes a same-uid, owner-only registry file under
``sideband_dir/instances/`` recording only routing identity: instance id,
pid, pid start-time (guards stale-PID-reuse liveness -- see
``_pid_is_live``), the socket/capability paths, and the set of thread ids
this instance's OWN extension traffic has bound (``thread/resume``/
``turn/start``/``turn/steer`` requests observed on the extension->child
pump -- never a sideband-issued call, which never passes through that
observer). ``callback_bridge.py``'s ``SidebandCallbackClient`` resolves
the unique live instance owning a given thread before addressing it;
missing, stale, or ambiguous ownership is a durable park
(``SidebandOwnerResolutionError``), never a guess and never a fan-out.
"""
